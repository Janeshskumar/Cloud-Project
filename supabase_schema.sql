-- Run this in Supabase Dashboard -> SQL Editor -> New query.
create table if not exists public.students (
  id bigint generated by default as identity primary key,
  name text not null,
  attendance double precision not null,
  study_hours double precision not null,
  previous_score double precision not null,
  assignment_score double precision not null,
  predicted_score double precision not null,
  performance text not null,
  created_at timestamptz not null default now()
);

-- Demo setup only: allow anonymous app access to read/insert/delete.
-- For production, disable these policies and use authenticated users + server-side service role.
alter table public.students enable row level security;
create policy "demo_read_students" on public.students for select to anon using (true);
create policy "demo_insert_students" on public.students for insert to anon with check (true);
create policy "demo_delete_students" on public.students for delete to anon using (true);
